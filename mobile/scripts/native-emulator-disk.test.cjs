'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

test('CI cleans unused host toolchains before native build and preserves Android PDF build dependencies', () => {
  const yaml = fs.readFileSync(path.resolve(__dirname, '../../.github/workflows/mobile-native-sqlcipher.yml'), 'utf8');
  const host = yaml.indexOf('- name: Reclaim unused hosted runner toolchains');
  const native = yaml.indexOf('- name: Compile standalone release APK');
  const saved = yaml.indexOf('- name: Save standalone emulator APK');
  const reclaim = yaml.indexOf('- name: Reclaim release intermediates before Android emulator');
  const maestro = yaml.indexOf('- name: Install checksum-verified pinned Maestro CLI');
  const smoke = yaml.indexOf('- name: Run real Android UI smoke');
  assert(host >= 0 && host < native && native < saved && saved < reclaim && reclaim < maestro && maestro < smoke);
  // Distribution failover cannot skip the emulator or trust unverified tools.
  const gradle = yaml.indexOf('- name: Install checksum-verified Gradle 8.13');
  const stage = yaml.indexOf('- name: Stage offline vision AAR');
  assert(gradle >= 0 && gradle < stage && stage < native);
  const audio = yaml.indexOf('- name: Stage checksum-verified upstream Audio API native binaries');
  assert(audio > host && audio < gradle);
  assert.match(yaml.slice(audio, gradle), /react-native-audio-api/);
  assert.match(yaml.slice(audio, gradle), /sha256sum --check --status/);
  assert.match(yaml.slice(audio, gradle), /unzip -tq/);
  assert.match(yaml.slice(audio, gradle), /libopusfile\.a/);
  assert.match(yaml.slice(audio, gradle), /libavcodec\.so/);
  assert.match(yaml.slice(audio, gradle), /Cannot verify pinned upstream Audio API/);
  assert.match(yaml.slice(gradle, stage), /sha256sum --check --status/);
  assert.match(yaml.slice(gradle, stage), /downloads\.gradle\.org\/distributions/);
  assert.match(yaml.slice(gradle, stage), /gradle-distributions\/releases/);
  assert.match(yaml.slice(gradle, stage), /gradle-9\.3\.1-bin/);
  assert.match(yaml.slice(gradle, stage), /trusted cached Gradle 9\.3\.1/);
  assert.match(yaml.slice(gradle, stage), /No verified Gradle 8\.13/);
  assert.match(yaml.slice(maestro, smoke), /sha256sum --check --status/);
  assert.match(yaml.slice(maestro, smoke), /mobile-dev-inc\/Maestro\/releases/);
  assert.match(yaml.slice(maestro, smoke), /test "\$MAESTRO_VERSION" = "2\.0\.10"/);
  const hostStep = yaml.slice(host, native);
  assert.match(hostStep, /\/usr\/share\/dotnet/);
  assert.match(hostStep, /\/usr\/share\/swift/);
  const clean = yaml.slice(reclaim, maestro);
  assert.match(clean, /test -s "\$apk"/);
  assert.match(clean, /android\/app\/build\/intermediates/);
  assert.match(clean, /df -Pk/);
  assert.match(clean, /Insufficient disk/);
  assert.doesNotMatch(clean, /rm -rf .*outputs/);
  assert.doesNotMatch(clean, /rm -rf .*ccache/);
  assert.doesNotMatch(clean, /rm -rf .*ndk/);
  assert.doesNotMatch(clean, /find "\$HOME\/\.gradle\/caches"/);
  assert.match(yaml.slice(smoke), /android-pdf-page-smoke\.sh/);
  assert.match(yaml.slice(smoke), /Require successful Android smoke/);
});
