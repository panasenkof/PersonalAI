import React from "react";
import { act, fireEvent, render, waitFor } from "@testing-library/react-native";
import { NoteAiEditor } from "../NoteAiEditor";
import { editNote } from "../../direct-agent/edit-note";
jest.mock("../../direct-agent/edit-note", () => ({ editNote: jest.fn() }));
jest.mock("../../direct-agent/settings", () => ({ loadDirectSettings: jest.fn(async () => ({})) }));
jest.mock("@react-navigation/native", () => ({ useIsFocused: () => true }));
jest.mock("../../local-memory/storage", () => ({ onLocalMemorySessionChange: () => () => {} }));
jest.mock("../VoiceInput", () => ({ VoiceInput: () => null }));
jest.mock("../BottomSheet", () => ({ BottomSheet: ({ children }: any) => <>{children}</> }));
jest.mock("../../theme", () => ({ useTheme: () => ({}) }));
const original = { title: "Заметка", body: "Исходный текст" };
const edited = { title: "Заметка", body: "Новый текст" };
const edit = editNote as jest.Mock;
beforeEach(() => jest.clearAllMocks());
test("model output is preview only until Apply and comparison preserves original", async () => {
  edit.mockResolvedValue(edited); const onApply = jest.fn(), onClose = jest.fn();
  const screen = render(<NoteAiEditor profile="p" draft={original} allowed onApply={onApply} onClose={onClose} />);
  fireEvent.changeText(screen.getByLabelText("Команда для редактирования заметки"), "Сократи");
  fireEvent.press(screen.getByLabelText("Запросить правку ИИ"));
  await waitFor(() => expect(screen.getByTestId("note-ai-preview").props.children).toBe(edited.body));
  expect(onApply).not.toHaveBeenCalled();
  fireEvent.press(screen.getByText("Сравнить с исходным"));
  expect(screen.getByTestId("note-ai-preview").props.children).toBe(original.body);
  fireEvent.press(screen.getByLabelText("Применить правку ИИ"));
  expect(onApply).toHaveBeenCalledWith(edited); expect(onClose).toHaveBeenCalled();
});
test("closing aborts and ignores late reply", async () => {
  let finish!: (value: typeof edited) => void;
  edit.mockImplementation(() => new Promise(resolve => { finish = resolve; }));
  const onApply = jest.fn(); const screen = render(<NoteAiEditor profile="p" draft={original} allowed onApply={onApply} onClose={jest.fn()} />);
  fireEvent.changeText(screen.getByLabelText("Команда для редактирования заметки"), "Сократи");
  fireEvent.press(screen.getByLabelText("Запросить правку ИИ"));
  await waitFor(() => expect(edit).toHaveBeenCalled());
  fireEvent.press(screen.getByLabelText("Отменить правку ИИ"));
  expect(edit.mock.calls[0][3].signal.aborted).toBe(true);
  await act(async () => finish(edited));
  expect(screen.queryByTestId("note-ai-preview")).toBeNull(); expect(onApply).not.toHaveBeenCalled();
});
test("editing draft while preview is open prevents stale Apply", async () => {
  edit.mockResolvedValue(edited); const onApply = jest.fn(), onClose = jest.fn();
  const screen = render(<NoteAiEditor profile="p" draft={original} allowed onApply={onApply} onClose={onClose} />);
  fireEvent.changeText(screen.getByLabelText("Команда для редактирования заметки"), "Сократи");
  fireEvent.press(screen.getByLabelText("Запросить правку ИИ"));
  await waitFor(() => expect(screen.getByTestId("note-ai-preview")).toBeTruthy());
  screen.rerender(<NoteAiEditor profile="p" draft={{ ...original, body: "Новая ручная правка" }} allowed onApply={onApply} onClose={onClose} />);
  fireEvent.press(screen.getByLabelText("Применить правку ИИ"));
  expect(onApply).not.toHaveBeenCalled(); expect(screen.getByText("Заметка изменилась. Повторите запрос.")).toBeTruthy();
});
